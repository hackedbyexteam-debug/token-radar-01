// The Launch Ledger's model, round 2: one snapshot in, one ranked board out.
//
// Implied value follows only from the snapshot's own figures, never from a
// hand-kept list of names:
//
//   peer     = median MCap/TVL of the token-bearing protocols in the same
//              category, shrunk toward the global median when peers are few
//   growth   = 1 + clamp(change_7d, -50, 120) / 100 * 0.5   (change_7d is PER CENT)
//   age      = 0.6 + min(age_days, 1095) / 1095 * 0.4        (unknown age: 365 days)
//   breadth  = 1 + 0.04 * min(chains, 4)
//   doubt    = 0.02 for an exchange, 0.03 for a wrapped / staked / bridged
//              product, 0.10 for a versioned pool, 1.00 otherwise
//   implied  = max(1, round(tvl * peer * growth * age * breadth * doubt))
//
// The board ranks every pre-token protocol in the snapshot (342 of them);
// the 40-protocol watchlist is the floor, never the ceiling. Live-token
// protocols are kept apart and shown at the market's own value.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

